class _GroupReducer:
    """Streaming groupby for data that does not fit in memory at raw row level.

    Partial aggregates are appended per chunk and re-reduced once they grow past
    ``max_rows``, so a group split across chunk boundaries still reduces exactly.
    """

    def __init__(self, keys: Sequence[str], how: str, max_rows: int = 12_000_000):
        self.keys = list(keys)
        self.how = how
        self.max_rows = max_rows
        self._parts: list[pd.DataFrame] = []
        self._rows = 0

    def add(self, frame: pd.DataFrame) -> None:
        if frame.empty:
            return
        self._parts.append(frame)
        self._rows += len(frame)
        if self._rows > self.max_rows:
            self._reduce()

    def _reduce(self) -> None:
        if len(self._parts) == 1 and self._rows <= self.max_rows:
            return
        merged = pd.concat(self._parts, ignore_index=True, copy=False)
        merged = merged.groupby(self.keys, sort=False, as_index=False).agg(self.how)
        self._parts = [merged]
        self._rows = len(merged)

    def result(self) -> pd.DataFrame:
        if not self._parts:
            return pd.DataFrame(columns=self.keys)
        self._reduce()
        return self._parts[0]


def _to_datetime(series: pd.Series) -> pd.Series:
    return pd.to_datetime(series, format=MIMIC_TIME_FORMAT, errors="coerce")


def _read_chunks(
    path: Path,
    usecols: Sequence[str],
    dtype: dict[str, str],
    chunksize: int,
    nrows: int | None = None,
) -> Iterable[pd.DataFrame]:
    reader = pd.read_csv(
        path,
        usecols=list(usecols),
        dtype=dtype,
        chunksize=chunksize,
        nrows=nrows,
    )
    for i, chunk in enumerate(reader, start=1):
        if i % 20 == 0:
            LOG.info("  %s: %s chunks read", path.name, f"{i:,}")
        yield chunk


def load_vitalsign(
    csv_dir: Path, chunksize: int = 2_000_000, nrows: int | None = None
) -> pd.DataFrame:
    """Rebuild ``mimiciv_derived.vitalsign`` from ``icu/chartevents.csv``.

    One row per (subject_id, stay_id, charttime); itemids mapping to the same
    concept are averaged, out-of-range values dropped before averaging.
    """
    path = csv_dir / "icu" / "chartevents.csv"
    LOG.info("vitalsign: scanning %s", path)
    sum_cols = [f"{v}_sum" for v in VITALS]
    n_cols = [f"{v}_n" for v in VITALS]
    keys = ["subject_id", "stay_id", "charttime"]
    reducer = _GroupReducer(keys, how="sum")

    for chunk in _read_chunks(
        path,
        usecols=["subject_id", "stay_id", "charttime", "itemid", "valuenum"],
        dtype={
            "subject_id": "int64",
            "stay_id": "float64",
            "itemid": "int32",
            "valuenum": "float32",
            "charttime": "string",
        },
        chunksize=chunksize,
        nrows=nrows,
    ):
        chunk = chunk[chunk["stay_id"].notna() & chunk["itemid"].isin(_VITAL_ITEMIDS)]
        if chunk.empty:
            continue
        chunk = chunk.assign(
            stay_id=chunk["stay_id"].astype("int64"),
            charttime=_to_datetime(chunk["charttime"]),
        )
        values = {}
        for name, (ids, low, high, inclusive) in VITAL_ITEMS.items():
            keep = chunk["itemid"].isin(ids) & (chunk["valuenum"] > low)
            keep &= chunk["valuenum"] <= high if inclusive else chunk["valuenum"] < high
            values[name] = chunk["valuenum"].where(keep)
        tidy = chunk[keys].assign(**values)
        grouped = tidy.groupby(keys, sort=False)[list(VITALS)]
        partial = pd.concat(
            [
                grouped.sum().set_axis(sum_cols, axis=1),
                grouped.count().set_axis(n_cols, axis=1),
            ],
            axis=1,
        ).reset_index()
        reducer.add(partial)

    agg = reducer.result()
    if agg.empty:
        return pd.DataFrame(columns=keys + list(VITALS))
    counts = agg[n_cols].to_numpy()
    sums = agg[sum_cols].to_numpy(dtype="float64")
    means = np.divide(sums, counts, out=np.full_like(sums, np.nan), where=counts > 0)
    out = agg[keys].copy()
    out[list(VITALS)] = means.astype("float32")
    out = out.sort_values(["stay_id", "charttime"], ignore_index=True)
    LOG.info("vitalsign: %s rows, %s stays", f"{len(out):,}", f"{out.stay_id.nunique():,}")
    return out


def load_chemistry(
    csv_dir: Path, chunksize: int = 4_000_000, nrows: int | None = None
) -> pd.DataFrame:
    """Rebuild the ``mimiciv_derived.chemistry`` columns TimeDiff uses.

    One row per specimen_id, as in concepts/measurement/chemistry.sql.  The
    reference only reads glucose, creatinine and sodium out of that table.
    """
    path = csv_dir / "hosp" / "labevents.csv"
    LOG.info("chemistry: scanning %s", path)
    keys = ["specimen_id"]
    carried = ["subject_id", "hadm_id", "charttime"]
    reducer = _GroupReducer(keys, how="max")

    for chunk in _read_chunks(
        path,
        usecols=["subject_id", "hadm_id", "specimen_id", "itemid", "charttime", "valuenum"],
        dtype={
            "subject_id": "int64",
            "hadm_id": "float64",
            "specimen_id": "int64",
            "itemid": "int32",
            "valuenum": "float32",
            "charttime": "string",
        },
        chunksize=chunksize,
        nrows=nrows,
    ):
        chunk = chunk[chunk["itemid"].isin(_LAB_ITEMIDS) & chunk["valuenum"].notna()]
        chunk = chunk[chunk["valuenum"] > 0]
        if chunk.empty:
            continue
        chunk = chunk.assign(charttime=_to_datetime(chunk["charttime"]))
        values = {}
        for name, (itemid, high) in LAB_ITEMS.items():
            keep = (chunk["itemid"] == itemid) & (chunk["valuenum"] <= high)
            values[name] = chunk["valuenum"].where(keep)
        tidy = chunk[keys + carried].assign(**values)
        partial = tidy.groupby(keys, sort=False, as_index=False).max()
        reducer.add(partial)

    agg = reducer.result()
    if agg.empty:
        return pd.DataFrame(columns=["subject_id", "charttime"] + list(LABS))
    out = agg[["subject_id", "charttime"] + list(LABS)].copy()
    out[list(LABS)] = out[list(LABS)].astype("float32")
    out = out.sort_values(["subject_id", "charttime"], ignore_index=True)
    LOG.info(
        "chemistry: %s specimens, %s subjects", f"{len(out):,}", f"{out.subject_id.nunique():,}"
    )
    return out


def select_stays(vitals: pd.DataFrame, min_measurements: int = 70) -> np.ndarray:
    """ICU stays with at least ``min_measurements`` charted values of every vital.

    The reference counts each vital separately with its own ``num >= 70`` filter
    and then intersects the five stay_id sets.
    """
    counts = vitals.groupby("stay_id")[list(VITALS)].count()
    eligible = counts.index[(counts >= min_measurements).all(axis=1)].to_numpy()
    for name in VITALS:
        LOG.info("  %s: %s stays >= %s values", name, f"{(counts[name] >= min_measurements).sum():,}", min_measurements)
    LOG.info("select_stays: %s stays in all five", f"{len(eligible):,}")
    return np.sort(eligible)


def _hourly_window(
    times: pd.DatetimeIndex,
    values: np.ndarray,
    round_to: str | None = None,
    n_steps: int = N_STEPS,
) -> np.ndarray | None:
    """First ``n_steps`` hours of ``values`` on an hourly grid, or None if too short.

    Equivalent to the reference's ``resample('H').asfreq()`` followed by a
    ``len(temp) >= n_steps`` test: the grid runs from the first to the last
    observation floored to the hour, and ``asfreq`` keeps only observations
    landing exactly on a grid point, so off-the-hour readings become missing.
    """
    if len(times) == 0:
        return None
    if round_to is not None:
        times = times.round(round_to)
    stamps = times.asi8
    order = np.argsort(stamps, kind="stable")
    stamps, values = stamps[order], np.asarray(values, dtype="float64")[order]
    unique = np.ones(len(stamps), dtype=bool)
    unique[1:] = stamps[1:] != stamps[:-1]
    stamps, values = stamps[unique], values[unique]

    start = stamps[0] - stamps[0] % _HOUR_NS
    last = stamps[-1] - stamps[-1] % _HOUR_NS
    if (last - start) // _HOUR_NS + 1 < n_steps:
        return None

    offset = stamps - start
    on_grid = (offset % _HOUR_NS == 0) & (offset < n_steps * _HOUR_NS)
    out = np.full(n_steps, np.nan)
    out[(offset[on_grid] // _HOUR_NS).astype(np.int64)] = values[on_grid]
    return out


def build_signal_channels(
    vitals: pd.DataFrame,
    chemistry: pd.DataFrame,
    stay_ids: np.ndarray,
    n_steps: int = N_STEPS,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Value + missingness channels for the eight signals, over the first 72 hours.

    A stay is dropped when any signal it does have spans fewer than ``n_steps``
    hours.  A lab the subject never had is kept as an all-missing channel pair.
    Vitals are looked up by stay, labs by subject, as in the reference.
    """
    vitals = vitals[vitals["stay_id"].isin(stay_ids)]
    stay_to_subject = (
        vitals.drop_duplicates("stay_id").set_index("stay_id")["subject_id"].to_dict()
    )
    vital_groups = dict(tuple(vitals.groupby("stay_id", sort=False)))
    subjects = set(stay_to_subject.values())
    chem_groups = dict(
        tuple(chemistry[chemistry["subject_id"].isin(subjects)].groupby("subject_id", sort=False))
    )

    kept_stays: list[int] = []
    kept_subjects: list[int] = []
    rows: list[np.ndarray] = []
    for n, stay_id in enumerate(stay_ids):
        if n and n % 2000 == 0:
            LOG.info("  channels %s / %s", f"{n:,}", f"{len(stay_ids):,}")
        subject_id = stay_to_subject[stay_id]
        stay_frame = vital_groups[stay_id]
        subject_frame = chem_groups.get(subject_id)

        channels: list[np.ndarray] = []
        for name in SIGNALS:
            is_lab = name in LAB_ITEMS
            frame = subject_frame if is_lab else stay_frame
            if frame is None or frame[name].notna().sum() == 0:
                if not is_lab:
                    channels = []
                    break
                series = np.full(n_steps, np.nan)
            else:
                observed = frame[[name]].dropna()
                series = _hourly_window(
                    pd.DatetimeIndex(frame.loc[observed.index, "charttime"]),
                    observed[name].to_numpy(),
                    round_to="20min" if is_lab else None,
                    n_steps=n_steps,
                )
                if series is None:
                    channels = []
                    break
            channels.append(series)
            channels.append(np.isnan(series).astype("float64"))

        if len(channels) != 2 * len(SIGNALS):
            continue
        rows.append(np.stack(channels))
        kept_stays.append(int(stay_id))
        kept_subjects.append(int(subject_id))

    if not rows:
        empty = np.empty((0, 2 * len(SIGNALS), n_steps), dtype="float32")
        return empty, np.empty(0, dtype="int64"), np.empty(0, dtype="int64")
    LOG.info("build_signal_channels: %s of %s stays kept", f"{len(rows):,}", f"{len(stay_ids):,}")
    return (
        np.stack(rows).astype("float32"),
        np.asarray(kept_stays, dtype="int64"),
        np.asarray(kept_subjects, dtype="int64"),
    )


def load_top_icd(csv_dir: Path, n_codes: int = N_STEPS) -> pd.DataFrame:
    """Binary subject x top-``n_codes`` ICD table.

    ``mimic4_save_icd.py`` ranks codes by how often they are coded and orders the
    matrix columns by that rank; the tensor then slices the first 72 columns.
    """
    path = csv_dir / "hosp" / "diagnoses_icd.csv"
    LOG.info("icd: reading %s", path)
    icd = pd.read_csv(path, usecols=["subject_id", "icd_code"], dtype={"subject_id": "int64", "icd_code": "string"})
    top = icd["icd_code"].value_counts().index[:n_codes]
    icd = icd[icd["icd_code"].isin(set(top))].drop_duplicates()
    rank = {code: i for i, code in enumerate(top)}
    table = np.zeros((icd["subject_id"].nunique(), n_codes), dtype="float32")
    subject_index = {s: i for i, s in enumerate(icd["subject_id"].unique())}
    table[
        icd["subject_id"].map(subject_index).to_numpy(),
        icd["icd_code"].map(rank).to_numpy(),
    ] = 1.0
    LOG.info("icd: top %s codes over %s subjects", n_codes, f"{len(subject_index):,}")
    return pd.DataFrame(table, index=pd.Index(list(subject_index), name="subject_id"))


def load_top_antibiotics(
    csv_dir: Path, n_drugs: int = N_STEPS, chunksize: int = 2_000_000
) -> pd.DataFrame:
    """Binary subject x top-``n_drugs`` antibiotic table.

    ``mimiciv_derived.antibiotic`` is rebuilt with the drug-name and route rules
    from concepts/medication/antibiotic.sql; drugs are then ranked by how many
    subjects received them, as in the reference.
    """
    path = csv_dir / "hosp" / "prescriptions.csv"
    LOG.info("antibiotic: scanning %s", path)
    pairs: list[pd.DataFrame] = []
    for chunk in _read_chunks(
        path,
        usecols=["subject_id", "drug", "drug_type", "route"],
        dtype={"subject_id": "int64", "drug": "string", "drug_type": "string", "route": "string"},
        chunksize=chunksize,
    ):
        chunk = chunk[chunk["drug"].notna() & chunk["route"].notna()]
        chunk = chunk[chunk["drug_type"] != "BASE"]
        route = chunk["route"].str.lower()
        chunk = chunk[
            ~chunk["route"].isin(_EXCLUDED_ROUTES)
            & ~route.str.contains("ear", na=False)
            & ~route.str.contains("eye", na=False)
        ]
        drug = chunk["drug"].str.lower()
        chunk = chunk[
            ~drug.str.contains("cream", na=False)
            & ~drug.str.contains("desensitization", na=False)
            & ~drug.str.contains("ophth oint", na=False)
            & ~drug.str.contains("gel", na=False)
        ]
        if chunk.empty:
            continue
        drug = chunk["drug"].str.lower()
        keep = drug.str.contains(_ANTIBIOTIC_PATTERN, regex=True, na=False)
        if not keep.any():
            continue
        pairs.append(chunk.loc[keep, ["subject_id", "drug"]].drop_duplicates())

    if not pairs:
        return pd.DataFrame(np.zeros((0, n_drugs), dtype="float32"), index=pd.Index([], name="subject_id"))
    abx = pd.concat(pairs, ignore_index=True).drop_duplicates()
    top = abx["drug"].value_counts().index[:n_drugs]
    abx = abx[abx["drug"].isin(set(top))]
    rank = {drug: i for i, drug in enumerate(top)}
    subject_index = {s: i for i, s in enumerate(abx["subject_id"].unique())}
    table = np.zeros((len(subject_index), n_drugs), dtype="float32")
    table[
        abx["subject_id"].map(subject_index).to_numpy(),
        abx["drug"].map(rank).to_numpy(),
    ] = 1.0
    LOG.info("antibiotic: top %s drugs over %s subjects", n_drugs, f"{len(subject_index):,}")
    return pd.DataFrame(table, index=pd.Index(list(subject_index), name="subject_id"))


def load_static(csv_dir: Path) -> tuple[pd.Series, set[int]]:
    """``anchor_age`` per subject and the subjects who died in hospital."""
    patients = pd.read_csv(
        csv_dir / "hosp" / "patients.csv",
        usecols=["subject_id", "anchor_age"],
        dtype={"subject_id": "int64", "anchor_age": "float32"},
    )
    age = patients.drop_duplicates("subject_id").set_index("subject_id")["anchor_age"]
    admissions = pd.read_csv(
        csv_dir / "hosp" / "admissions.csv",
        usecols=["subject_id", "hospital_expire_flag"],
        dtype={"subject_id": "int64", "hospital_expire_flag": "float32"},
    )
    expired = set(admissions.loc[admissions["hospital_expire_flag"] == 1, "subject_id"])
    LOG.info("static: %s subjects with age, %s expired", f"{len(age):,}", f"{len(expired):,}")
    return age, expired


def add_static_channels(
    signals: np.ndarray,
    subject_ids: np.ndarray,
    icd: pd.DataFrame,
    antibiotics: pd.DataFrame,
    age: pd.Series,
    expired: set[int],
) -> np.ndarray:
    """Append the four channels that are constant over the 72 hours."""
    n, _, n_steps = signals.shape
    icd_rows = icd.reindex(subject_ids).fillna(0.0).to_numpy(dtype="float32")
    abx_rows = antibiotics.reindex(subject_ids).fillna(0.0).to_numpy(dtype="float32")
    age_rows = np.repeat(
        age.reindex(subject_ids).fillna(0.0).to_numpy(dtype="float32")[:, None], n_steps, axis=1
    )
    mort_rows = np.repeat(
        np.isin(subject_ids, list(expired)).astype("float32")[:, None], n_steps, axis=1
    )
    statics = np.stack([icd_rows, abx_rows, age_rows, mort_rows], axis=1)
    LOG.info("add_static_channels: mortality rate %.3f", mort_rows[:, 0].mean() if n else 0.0)
    return np.concatenate([signals, statics], axis=1)


def split_train_test(
    tensor: np.ndarray, stay_ids: np.ndarray, seed: int = 2023, train_frac: float = 0.75
) -> dict[str, np.ndarray]:
    """75/25 split stratified on the mortality channel, as in the reference.

    The reference defers to ``sklearn.train_test_split``; this is an equivalent
    numpy implementation so the module needs no scikit-learn, and the assignment
    of individual stays therefore differs from the reference run.
    """
    rng = np.random.default_rng(seed)
    order = rng.permutation(len(tensor))
    tensor, stay_ids = tensor[order], stay_ids[order]

    labels = tensor[:, -1, 0]
    n_test = len(tensor) - int(len(tensor) * train_frac)
    classes, counts = np.unique(labels, return_counts=True)
    quota = counts * n_test / len(tensor)
    per_class = np.floor(quota).astype(int)
    short = n_test - per_class.sum()
    if short > 0:
        for i in np.argsort(-(quota - per_class))[:short]:
            per_class[i] += 1

    test_idx: list[np.ndarray] = []
    for label, take in zip(classes, per_class):
        members = np.flatnonzero(labels == label)
        test_idx.append(rng.permutation(members)[:take])
    test_mask = np.zeros(len(tensor), dtype=bool)
    test_mask[np.concatenate(test_idx)] = True

    return {
        "train": tensor[~test_mask],
        "test": tensor[test_mask],
        "stays_train": stay_ids[~test_mask],
        "stays_test": stay_ids[test_mask],
    }


def channel_names() -> list[str]:
    names = [f"{s}{suffix}" for s in SIGNALS for suffix in ("", "_mask")]
    return names + list(STATIC_CHANNELS)


