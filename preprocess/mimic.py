# -*- coding: utf-8 -*-
"""MIMIC-IV ICU time-series extraction, translated from TimeDiff.

Reference: TimeDiff `preprocess/mimic4_everything.ipynb` (the vital/lab
extraction is shared with `mimic4_time_irregular_icd.ipynb`, the ICD matrix with
`preprocess/mimic4_save_icd.py`).  The reference reads a local PostgreSQL MIMIC-IV
through `helpers.DataBaseLoader`, querying the `mimiciv_derived.vitalsign`,
`mimiciv_derived.chemistry`, `mimiciv_derived.antibiotic`, `mimiciv_hosp.admissions`
and `mimiciv_hosp.patients` tables.

This module reproduces that preprocessing from the PhysioNet CSV distribution
instead, so no database is required.  The three `mimiciv_derived` tables are not
part of the CSV download, so they are rebuilt here from `icu/chartevents.csv`,
`hosp/labevents.csv` and `hosp/prescriptions.csv` following the MIT-LCP concept
definitions they are generated by (`mimic-iv/concepts/measurement/vitalsign.sql`,
`.../chemistry.sql`, `mimic-iv/concepts/medication/antibiotic.sql`).

Pipeline (each step matches the reference):

1. Pivot chartevents into one row per (subject_id, stay_id, charttime) with the
   five vitals TimeDiff uses, averaging duplicate itemids at one charttime.
2. Pivot labevents into one row per specimen with glucose / creatinine / sodium.
3. Keep ICU stays with >= 70 charted values of every vital; labs only need one.
4. Resample each signal onto an hourly grid and keep the first 72 hours.  Each
   signal contributes a value channel and a missing-value mask channel.
5. Append four non-temporal channels.  Age and mortality are held constant over
   the 72 slots; the ICD and antibiotic channels instead abuse the 72 slots to
   carry a 72-long binary indicator over the most frequent codes/drugs, which is
   what the reference does.
6. Split 75/25 stratified on mortality and save .npy tensors.

Outputs, written to `--out-dir` (default `processed_mimic/`):

* `train.npy` / `test.npy` -- float32 `(n_stays, 20, 72)`, one row per ICU stay,
  75% / 25% of the cohort.  Axis 1 is the channel, axis 2 is hours 0..71.  Each
  signal is windowed from its own first observation rather than from a clock
  shared by the stay, so the channels of one row are not mutually aligned in
  absolute time; the reference resamples each series independently likewise.
  Channels, in order:
      0..9   vitals as value/mask pairs: heart_rate, sbp, dbp, resp_rate, spo2
      10..15 labs as value/mask pairs: glucose, creatinine, sodium
      16     icd        binary over the 72 most frequent ICD codes
      17     antibiotic binary over the 72 most frequent antibiotics
      18     age        anchor_age, repeated across all 72 hours
      19     mortality  hospital_expire_flag, repeated across all 72 hours
  Value channels hold NaN where nothing was measured on that hour; the mask
  channel next to each is 1 exactly there and 0 where a value is present.  A
  signal never observed for a stay is an all-NaN channel with an all-ones mask,
  which is why the lab channels are mostly masked.  Indices 16 and 17 are
  indexed by code rank, not by hour; 18 and 19 are constant along axis 2.
  `channel_names()` returns these 20 names in order.
* `stays_train.npy` / `stays_test.npy` -- int64 `(n_stays,)`, the MIMIC-IV
  `stay_id` of each row of the corresponding tensor, in the same order.  Rows
  are shuffled by the split, so these are needed to join back to MIMIC.
* `channels.json` -- the channel names, cohort sizes and the settings used.
* `annotations.json` -- per-stay status labels for the same cohort, keyed by
  `stay_id`, with a `fields` block describing each one and `label_rates` giving
  the positive rate of every binary label.  Nothing here feeds the tensors; it
  is the outcome and diagnosis metadata the CSV release carries, collected so
  the stays can be conditioned on or evaluated against more than the single
  in-hospital mortality bit in channel 20.  Covers mortality (in-hospital, in-ICU,
  30-day and 1-year from `patients.dod`, which also catches the ~26k deaths that
  happen after discharge), discharge destination, 30-day readmission, length of
  stay, care unit, service line, APR-DRG severity and risk of mortality, and the
  admission's ICD codes with the primary one resolved to its title.

Deliberate departures from the reference, which cannot be reproduced exactly:

* Lab timestamps are rounded to 20 minutes and then de-duplicated.  The
  reference keeps whichever row Postgres returned first, which is unordered;
  here the earliest original timestamp wins.
* A subject whose antibiotics all fall outside the top 72 gets a zero channel.
  The reference appends no channel at all and so silently drops the stay.
* ICD codes are ranked by raw `icd_code`; the reference re-inserts an ICD-9
  decimal point first, which changes the label but not the ranking.
* Tensor channel 20 is the reference's subject-level mortality: it is 1 when the
  subject died in *any* admission, not necessarily the one being modelled.
  `annotations.json` carries the admission-level flag under the same name, and
  the two disagree for a few percent of stays; the annotation is the correct one.

Usage:
    python mimic.py --csv-dir physionet.org/files/mimiciv/3.1 --out-dir processed_mimic
"""

